const dataSourceGCPKMSKeyManagerDescription = `
The ´rubrik_gcp_kms_key_manager´ data source is used to look up a single GCP
Cloud KMS key manager registered in RSC, by name or by ID.

A key manager is a stored connection profile giving RSC access to a customer
owned key management service. Its ID is generated by RSC and is the value
archival locations refer to the key manager by, alongside the name and version
of the crypto key itself, which come from GCP.

~> **Note:** Key managers are registered in the RSC UI, under Settings,
   Security, Encryption Management. There is no Terraform resource for
   registering one.
`

var (
	_ datasource.DataSource              = &gcpKMSKeyManagerDataSource{}
	_ datasource.DataSourceWithConfigure = &gcpKMSKeyManagerDataSource{}
)

type gcpKMSKeyManagerDataSource struct {
	client *client
	prefix string
}

type gcpKMSKeyManagerModel struct {
	ID                 types.String `tfsdk:"id"`
	Name               types.String `tfsdk:"name"`
	Description        types.String `tfsdk:"description"`
	ProvisioningMethod types.String `tfsdk:"provisioning_method"`
	NaturalID          types.String `tfsdk:"natural_id"`
	DataLocationsCount types.Int64  `tfsdk:"data_locations_count"`
	CloudAccountID     types.String `tfsdk:"cloud_account_id"`
	Region             types.String `tfsdk:"region"`
	KeyRing            types.String `tfsdk:"key_ring"`
}

func newGCPKMSKeyManagerDataSource() datasource.DataSource {
	return &gcpKMSKeyManagerDataSource{prefix: keyRubrik}
}

func newPolarisGCPKMSKeyManagerDataSource() datasource.DataSource {
	return &gcpKMSKeyManagerDataSource{prefix: keyPolaris}
}

func (d *gcpKMSKeyManagerDataSource) Metadata(ctx context.Context, req datasource.MetadataRequest, res *datasource.MetadataResponse) {
	tflog.Trace(ctx, "gcpKMSKeyManagerDataSource.Metadata")

	res.TypeName = d.prefix + "_" + keyGCPKMSKeyManager
}

func (d *gcpKMSKeyManagerDataSource) Schema(ctx context.Context, _ datasource.SchemaRequest, res *datasource.SchemaResponse) {
	tflog.Trace(ctx, "gcpKMSKeyManagerDataSource.Schema")

	res.Schema = schema.Schema{
		Description: description(dataSourceGCPKMSKeyManagerDescription),
		Attributes: map[string]schema.Attribute{
			keyID: schema.StringAttribute{
				Optional: true,
				Computed: true,
				Description: "RSC key manager ID (UUID). This is the value archival locations refer to the key " +
					"manager by. Exactly one of `id` and `name` must be specified.",
				Validators: []validator.String{
					isUUID(),
					stringvalidator.ExactlyOneOf(path.MatchRoot(keyID), path.MatchRoot(keyName)),
				},
			},
			keyName: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "Key manager name. Exactly one of `id` and `name` must be specified.",
				Validators: []validator.String{
					isNotWhiteSpace(),
				},
			},
			keyDescription: schema.StringAttribute{
				Computed:    true,
				Description: "Key manager description.",
			},
			keyProvisioningMethod: schema.StringAttribute{
				Computed: true,
				Description: fmt.Sprintf("How RSC obtains the credentials it reaches Cloud KMS with. %s.",
					possibleValues(gqlkms.ProvisioningMethodValues(core.CloudVendorGCP))),
			},
			keyNaturalID: schema.StringAttribute{
				Computed: true,
				Description: "Identifies what the key manager connects to, rather than the key manager itself: " +
					"the key ring name.",
			},
			keyDataLocationsCount: schema.Int64Attribute{
				Computed:    true,
				Description: "Number of data locations encrypted with keys from this key manager.",
			},
			keyCloudAccountID: schema.StringAttribute{
				Computed:    true,
				Description: "RSC cloud account ID of the GCP project holding the key ring.",
			},
			keyRegion: schema.StringAttribute{
				Computed:    true,
				Description: "Cloud KMS location of the key ring.",
			},
			keyKeyRing: schema.StringAttribute{
				Computed:    true,
				Description: "Key ring name.",
			},
		},
	}

	if d.prefix == keyPolaris {
		res.Schema.DeprecationMessage = "use the `rubrik_gcp_kms_key_manager` data source instead."
	}
}

func (d *gcpKMSKeyManagerDataSource) Configure(ctx context.Context, req datasource.ConfigureRequest, _ *datasource.ConfigureResponse) {
	tflog.Trace(ctx, "gcpKMSKeyManagerDataSource.Configure")

	if req.ProviderData == nil {
		return
	}
	d.client = req.ProviderData.(*client)
}

func (d *gcpKMSKeyManagerDataSource) Read(ctx context.Context, req datasource.ReadRequest, res *datasource.ReadResponse) {
	tflog.Trace(ctx, "gcpKMSKeyManagerDataSource.Read")

	var config gcpKMSKeyManagerModel
	res.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if res.Diagnostics.HasError() {
		return
	}

	polarisClient, err := d.client.polaris()
	if err != nil {
		res.Diagnostics.AddError("RSC client error", err.Error())
		return
	}

	var keyManager gqlkms.KeyManager
	if id := config.ID.ValueString(); id != "" {
		keyManagerID, parseErr := uuid.Parse(id)
		if parseErr != nil {
			res.Diagnostics.AddError("Failed to parse key manager ID", parseErr.Error())
			return
		}
		keyManager, err = kms.Wrap(polarisClient).GCPKeyManagerByID(ctx, keyManagerID)
	} else {
		keyManager, err = kms.Wrap(polarisClient).GCPKeyManagerByName(ctx, config.Name.ValueString())
	}
	if errors.Is(err, graphql.ErrNotFound) {
		res.Diagnostics.AddError("KMS key manager not found", err.Error())
		return
	}
	if err != nil {
		res.Diagnostics.AddError("Failed to read KMS key manager", err.Error())
		return
	}

	state := gcpKMSKeyManagerModel{
		ID:                 types.StringValue(keyManager.KeyVaultInfo.ID.String()),
		Name:               types.StringValue(keyManager.Name),
		Description:        types.StringValue(keyManager.Description),
		ProvisioningMethod: types.StringValue(string(keyManager.KeyVaultInfo.ProvisioningMethod)),
		NaturalID:          types.StringValue(keyManager.NaturalID),
		DataLocationsCount: types.Int64Value(int64(keyManager.DataLocationsCount)),
		CloudAccountID:     types.StringValue(keyManager.KeyVaultInfo.CloudAccountID),
		Region:             types.StringValue(keyManager.KeyVaultInfo.GCPLocation.Name()),
		KeyRing:            types.StringValue(keyManager.KeyVaultInfo.KeyRing),
	}

	res.Diagnostics.Append(res.State.Set(ctx, &state)...)
}
