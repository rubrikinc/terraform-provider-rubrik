const dataSourceAzureKMSKeyManagerDescription = `
The ´rubrik_azure_kms_key_manager´ data source is used to look up a single Azure
key vault key manager registered in RSC, by name or by ID.

A key manager is a stored connection profile giving RSC access to a customer
owned key management service. Its ID is generated by RSC and is the value
archival locations refer to the key manager by, alongside the name and version
of the key itself, which come from Azure.

~> **Note:** Key managers are registered with the ´rubrik_azure_kms_key_manager´
   resource or in the RSC UI, under Settings, Security, Encryption Management.
   The data source finds a key manager registered either way.
`

var (
	_ datasource.DataSource              = &azureKMSKeyManagerDataSource{}
	_ datasource.DataSourceWithConfigure = &azureKMSKeyManagerDataSource{}
)

type azureKMSKeyManagerDataSource struct {
	client *client
	prefix string
}

type azureKMSKeyManagerModel struct {
	ID                 types.String `tfsdk:"id"`
	Name               types.String `tfsdk:"name"`
	Description        types.String `tfsdk:"description"`
	ProvisioningMethod types.String `tfsdk:"provisioning_method"`
	NaturalID          types.String `tfsdk:"natural_id"`
	DataLocationsCount types.Int64  `tfsdk:"data_locations_count"`
	CloudAccountID     types.String `tfsdk:"cloud_account_id"`
	Region             types.String `tfsdk:"region"`
	KeyVaultURL        types.String `tfsdk:"key_vault_url"`
	TenantID           types.String `tfsdk:"tenant_id"`
	ClientID           types.String `tfsdk:"client_id"`
}

func newAzureKMSKeyManagerDataSource() datasource.DataSource {
	return &azureKMSKeyManagerDataSource{prefix: keyRubrik}
}

func newPolarisAzureKMSKeyManagerDataSource() datasource.DataSource {
	return &azureKMSKeyManagerDataSource{prefix: keyPolaris}
}

func (d *azureKMSKeyManagerDataSource) Metadata(ctx context.Context, req datasource.MetadataRequest, res *datasource.MetadataResponse) {
	tflog.Trace(ctx, "azureKMSKeyManagerDataSource.Metadata")

	res.TypeName = d.prefix + "_" + keyAzureKMSKeyManager
}

func (d *azureKMSKeyManagerDataSource) Schema(ctx context.Context, _ datasource.SchemaRequest, res *datasource.SchemaResponse) {
	tflog.Trace(ctx, "azureKMSKeyManagerDataSource.Schema")

	res.Schema = schema.Schema{
		Description: description(dataSourceAzureKMSKeyManagerDescription),
		Attributes: map[string]schema.Attribute{
			keyID: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "RSC key manager ID (UUID). Exactly one of `id` and `name` must be specified.",
				Validators: []validator.String{
					isUUID(),
					stringvalidator.ExactlyOneOf(path.MatchRoot(keyID), path.MatchRoot(keyName)),
				},
			},
			keyName: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "Key manager name. Exactly one of `id` and `name` must be specified.",
				Validators: []validator.String{
					isNotWhiteSpace(),
				},
			},
			keyDescription: schema.StringAttribute{
				Computed:    true,
				Description: "Key manager description.",
			},
			keyProvisioningMethod: schema.StringAttribute{
				Computed: true,
				Description: fmt.Sprintf("How RSC obtains the credentials it reaches the key vault with. %s.",
					possibleValues(gqlkms.ProvisioningMethodValues(core.CloudVendorAzure))),
			},
			keyNaturalID: schema.StringAttribute{
				Computed: true,
				Description: "Identifies what the key manager connects to, rather than the key manager itself: " +
					"the key vault URL.",
			},
			keyDataLocationsCount: schema.Int64Attribute{
				Computed:    true,
				Description: "Number of data locations encrypted with keys from this key manager.",
			},
			keyCloudAccountID: schema.StringAttribute{
				Computed: true,
				Description: "RSC cloud account ID backing the key manager. Empty unless `provisioning_method` " +
					"is `CLOUD_ACCOUNT_PROVISION`.",
			},
			keyRegion: schema.StringAttribute{
				Computed:    true,
				Description: "Azure region of the key vault, e.g. `eastus2`.",
			},
			keyKeyVaultURL: schema.StringAttribute{
				Computed:    true,
				Description: "Key vault URL.",
			},
			keyTenantID: schema.StringAttribute{
				Computed:    true,
				Description: "Azure tenant ID.",
			},
			keyClientID: schema.StringAttribute{
				Computed:    true,
				Description: "Azure client ID.",
			},
		},
	}

	if d.prefix == keyPolaris {
		res.Schema.DeprecationMessage = "use the `rubrik_azure_kms_key_manager` data source instead."
	}
}

func (d *azureKMSKeyManagerDataSource) Configure(ctx context.Context, req datasource.ConfigureRequest, _ *datasource.ConfigureResponse) {
	tflog.Trace(ctx, "azureKMSKeyManagerDataSource.Configure")

	if req.ProviderData == nil {
		return
	}
	d.client = req.ProviderData.(*client)
}

func (d *azureKMSKeyManagerDataSource) Read(ctx context.Context, req datasource.ReadRequest, res *datasource.ReadResponse) {
	tflog.Trace(ctx, "azureKMSKeyManagerDataSource.Read")

	var config azureKMSKeyManagerModel
	res.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if res.Diagnostics.HasError() {
		return
	}

	polarisClient, err := d.client.polaris()
	if err != nil {
		res.Diagnostics.AddError("RSC client error", err.Error())
		return
	}

	var keyManager gqlkms.KeyManager
	if id := config.ID.ValueString(); id != "" {
		keyManagerID, parseErr := uuid.Parse(id)
		if parseErr != nil {
			res.Diagnostics.AddError("Failed to parse key manager ID", parseErr.Error())
			return
		}
		keyManager, err = kms.Wrap(polarisClient).AzureKeyManagerByID(ctx, keyManagerID)
	} else {
		keyManager, err = kms.Wrap(polarisClient).AzureKeyManagerByName(ctx, config.Name.ValueString())
	}
	if errors.Is(err, graphql.ErrNotFound) {
		res.Diagnostics.AddError("KMS key manager not found", err.Error())
		return
	}
	if err != nil {
		res.Diagnostics.AddError("Failed to read KMS key manager", err.Error())
		return
	}

	state := azureKMSKeyManagerModel{
		ID:                 types.StringValue(keyManager.KeyVaultInfo.ID.String()),
		Name:               types.StringValue(keyManager.Name),
		Description:        types.StringValue(keyManager.Description),
		ProvisioningMethod: types.StringValue(string(keyManager.KeyVaultInfo.ProvisioningMethod)),
		NaturalID:          types.StringValue(keyManager.NaturalID),
		DataLocationsCount: types.Int64Value(int64(keyManager.DataLocationsCount)),
		CloudAccountID:     types.StringValue(keyManager.KeyVaultInfo.CloudAccountID),
		Region:             types.StringValue(keyManager.KeyVaultInfo.AzureRegion.Name()),
		KeyVaultURL:        types.StringValue(keyManager.KeyVaultInfo.KeyVaultURL),
		TenantID:           types.StringValue(keyManager.KeyVaultInfo.TenantID),
		ClientID:           types.StringValue(keyManager.KeyVaultInfo.ClientID),
	}

	res.Diagnostics.Append(res.State.Set(ctx, &state)...)
}
